export type OutageDomain = {
  sk: string,                   // "OUTAGE#<outageId>"
  entityType: "OUTAGE",
  outageId: string,             // UUID, generated by the server
  resourceType: string,         // "UNIT" | "GANG"
  resourceId: string,           // The unitId or gangId that is offline
  reason: string,               // e.g. "Maintenance" | "Equipment malfunction" | "Labor shortage" | free text
  startAt: string,              // "YYYY-MM-DDTHH:mm:00", local time; start of the first occurrence
  endAt: string,                // "YYYY-MM-DDTHH:mm:00", local time; end of the first occurrence
  active: boolean,              // false = ignored (soft delete)

  // Omit recurrence for a one-off outage
  recurrence?: {
    frequency: string,          // "DAILY" | "WEEKLY" | "MONTHLY" | "YEARLY"
    interval: number,           // Every X days / weeks / months / years, 1–99

    // Weekly (required)
    daysOfWeek?: string[],      // ["MON", "WED"]

    // Monthly (cycle required)
    cycle?: string,             // "EACH" | "ON_THE"
    daysOfMonth?: number[],     // [10, 27] when cycle = "EACH"
    weekNumber?: string,        // "FIRST" | "SECOND" | "THIRD" | "FOURTH" | "LAST", when cycle = "ON_THE"
    dayOfWeek?: string,         // "MON" … "SUN", when cycle = "ON_THE"

    // Yearly (months required)
    months?: number[],          // [6, 12] = June and December
    // Can also use cycle "ON_THE" + weekNumber + dayOfWeek for yearly

    until?: string,             // "YYYY-MM-DD", last date it can repeat. Omit = no end
  },
}