export type GangDomain = {
  sk: string,                   // "GANG#<gangId>"
  entityType: "GANG",
  gangId: string,               // UUID, generated by the server
  name: string,                 // e.g. "Gang A". Unique per terminal
  equipmentTypes: string[],     // Types this gang may run, e.g. ["HEAVY_LIFT_CRANE", "CRANE"]. At least 1
  active: boolean,              // false = never assigned (soft delete)
  notes?: string,               // Up to 500 characters
}