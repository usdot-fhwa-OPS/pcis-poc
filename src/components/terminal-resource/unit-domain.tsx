export type UnitDomain = {
  sk: string,                   // "UNIT#<unitId>"
  entityType: "UNIT",
  unitId: string,               // UUID, generated by the server
  name: string,                 // e.g. "Forklift 2". Unique per terminal
  equipmentType: string,        // Must match an active EQTYPE, e.g. "FORKLIFT"
  inService: boolean,           // false = removed long-term; short breaks are OUTAGEs
  defaultDurationMins?: number, // Overrides the type's default for this unit only
  notes?: string,               // Up to 500 characters
}